function changeLanguage() {
    const languageElement = document.getElementById('language');
    if (!languageElement) return; 
    
    const lang = languageElement.value;
    localStorage.setItem('selectedLanguage', lang);
    const translation = translations[lang];

    if (!translation) return; 

    
    document.querySelectorAll('[id]').forEach(element => {
        const id = element.id;
    
        if (translation[id] && element.tagName !== 'INPUT' && element.tagName !== 'SELECT' && element.tagName !== 'TEXTAREA') {
            element.textContent = translation[id];
        }
    });

    
    if (document.getElementById('patient-room')) {
        document.getElementById('patient-room').placeholder = translation['patient-room-label'];
    }
    if (document.getElementById('patient-password')) {
        document.getElementById('patient-password').placeholder = translation['patient-password-label'];
    }
    if (document.getElementById('staff-username')) {
        document.getElementById('staff-username').placeholder = translation['staff-username-label'];
    }
    if (document.getElementById('staff-password')) {
        document.getElementById('staff-password').placeholder = translation['staff-password-label'];
    }
    if (document.getElementById('dietary-restrictions')) {
        document.getElementById('dietary-restrictions').placeholder = translation['dietary-restrictions-label'];
    }
    if (document.getElementById('meal-management')) {
        document.getElementById('meal-management').placeholder = translation['manage-meals'];
    }
}


window.onload = function() {
    const savedLanguage = localStorage.getItem('selectedLanguage') || 'en';
    const languageElement = document.getElementById('language');
    
    if (languageElement) {
        languageElement.value = savedLanguage;
        changeLanguage();
    }
};